const escapeHTML = value => String(value ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
export const plateById = id => PLATES.find(plate => plate.id === id) || null;
export function platesFor(kind, value) {
  return PLATES.filter(plate => (plate[kind] || []).includes(value)).map(plate => plate.id);
}

function figure(plate) {
  return `<figure class="plate-card" data-plate-id="${escapeHTML(plate.id)}">
    <button type="button" class="plate-image-button" data-plate-open="${escapeHTML(plate.id)}" aria-label="Ampliar prancha: ${escapeHTML(plate.title)}">
      <img src="${escapeHTML(plate.src)}" alt="${escapeHTML(plate.alt)}" width="${plate.width}" height="${plate.height}" loading="lazy" decoding="async">
      <span class="plate-image-hint">Ampliar figura ↗</span>
    </button>
    <figcaption><span class="plate-category">${escapeHTML(plate.group)}</span><h3>${escapeHTML(plate.title)}</h3><p>${escapeHTML(plate.caption)}</p>
      <div class="plate-links"><button type="button" class="plate-link-button" data-plate-open="${escapeHTML(plate.id)}">Ver em tamanho ampliado</button>${plate.lab ? `<button type="button" class="plate-link-button" data-action="atlas-experiment:${escapeHTML(plate.lab)}">Praticar no ImunoLab →</button>` : ''}</div>
    </figcaption>
  </figure>`;
}

export function renderPlateCollection(ids, {title = 'Pranchas de apoio ao tema', collapsed = false} = {}) {
  const selected = [...new Set(ids)].map(plateById).filter(Boolean);
  if (!selected.length) return '';
  const cards = `<div class="plate-grid ${selected.length === 1 ? 'plate-grid-single' : ''}">${selected.map(figure).join('')}</div>`;
  if (collapsed) return `<details class="plate-support"><summary><span>PRANCHAS DE APOIO</span><strong>${escapeHTML(title)}</strong><small>${selected.length} ${selected.length === 1 ? 'prancha' : 'pranchas'} · abrir para consultar</small></summary>${cards}</details>`;
  return `<section class="plate-collection" aria-label="${escapeHTML(title)}"><header class="plate-section-heading"><span class="mini-label">PRANCHAS CIENTÍFICAS</span><h2>${escapeHTML(title)}</h2><p>Selecione uma imagem para ampliar. As legendas e os detalhes das figuras podem ser consultados com os controles de zoom.</p></header>${cards}</section>`;
}

export function renderPlateGallery() {
  const groups = [...new Set(PLATES.map(plate => plate.group))];
  return `<section class="plate-gallery" aria-label="Coleção de pranchas temáticas"><header class="plate-section-heading"><span class="mini-label">ATLAS VISUAL · ${PLATES.length} PRANCHAS</span><h2>Imunologia em figuras</h2><p>Uma coleção organizada por assunto, também disponível junto aos mecanismos, oficinas e experimentos correspondentes.</p><nav class="plate-group-nav" aria-label="Temas das pranchas">${groups.map((group, i) => `<a href="#plate-group-${i}">${escapeHTML(group)}</a>`).join('')}</nav></header>${groups.map((group, i) => `<section id="plate-group-${i}" class="plate-gallery-group"><h2>${escapeHTML(group)}</h2><div class="plate-grid">${PLATES.filter(plate => plate.group === group).map(figure).join('')}</div></section>`).join('')}<p class="plate-source-note">Pranchas fornecidas pela autora, preservadas na íntegra. Ilustrações esquemáticas para estudo; consulte as explicações das atividades e as orientações da disciplina.</p></section>`;
}

/** Dialog fora da raiz da aplicação para não interromper sessões ou apagar respostas. */
export function bindPlateViewer(doc = document) {
  if (doc.getElementById('plate-viewer')) return;
  const viewer = doc.createElement('dialog');
  viewer.id = 'plate-viewer';
  viewer.className = 'plate-viewer';
  viewer.setAttribute('aria-labelledby', 'plate-viewer-title');
  viewer.innerHTML = `<header class="plate-viewer-head"><div><span id="plate-viewer-count" class="plate-category"></span><h2 id="plate-viewer-title"></h2></div><button type="button" data-plate-control="close" aria-label="Fechar prancha">✕</button></header><div class="plate-viewer-tools" role="group" aria-label="Controles de ampliação"><button type="button" data-plate-control="prev" aria-label="Prancha anterior">← Anterior</button><button type="button" data-plate-control="next" aria-label="Próxima prancha">Próxima →</button><span class="plate-tools-divider"></span><button type="button" data-plate-control="minus" aria-label="Diminuir zoom">−</button><output id="plate-viewer-zoom" aria-live="polite">100%</output><button type="button" data-plate-control="plus" aria-label="Aumentar zoom">+</button><button type="button" data-plate-control="fit">Ajustar à tela</button><a id="plate-viewer-original" target="_blank" rel="noopener noreferrer">Abrir imagem ↗</a></div><div class="plate-viewer-canvas" tabindex="0" aria-label="Imagem ampliada; utilize a rolagem para explorar"><img id="plate-viewer-image" alt=""></div><p id="plate-viewer-caption" class="plate-viewer-caption"></p>`;
  doc.body.append(viewer);
  let selectedIndex = 0, zoom = 1, opener = null, originalOverflow = '';
  const find = selector => viewer.querySelector(selector);
  const canvas = find('.plate-viewer-canvas');
  const img = find('#plate-viewer-image');

  function setZoom(next) {
    zoom = Math.max(1, Math.min(3, next));
    img.style.width = `${zoom * 100}%`;
    find('#plate-viewer-zoom').textContent = `${Math.round(zoom * 100)}%`;
    find('[data-plate-control="minus"]').disabled = zoom <= 1;
    find('[data-plate-control="plus"]').disabled = zoom >= 3;
  }
  function show(index) {
    selectedIndex = (index + PLATES.length) % PLATES.length;
    const plate = PLATES[selectedIndex];
    img.src = plate.src;
    img.alt = plate.alt;
    find('#plate-viewer-title').textContent = plate.title;
    find('#plate-viewer-count').textContent = `${selectedIndex + 1}/${PLATES.length} · ${plate.group}`;
    find('#plate-viewer-caption').textContent = plate.caption;
    find('#plate-viewer-original').href = plate.src;
    setZoom(1);
    canvas.scrollTop = canvas.scrollLeft = 0;
  }
  function close() {
    if (typeof viewer.close === 'function') viewer.close();
    else { viewer.removeAttribute('open'); restoreFocus(); }
  }
  function restoreFocus() {
    doc.documentElement.style.overflow = originalOverflow;
    if (opener?.isConnected) opener.focus({preventScroll: true});
  }
  viewer.addEventListener('close', restoreFocus);
  viewer.addEventListener('click', event => {
    const button = event.target.closest('[data-plate-control]');
    if (!button) { if (event.target === viewer) close(); return; }
    const control = button.dataset.plateControl;
    if (control === 'close') close();
    else if (control === 'plus') setZoom(zoom + 0.25);
    else if (control === 'minus') setZoom(zoom - 0.25);
    else if (control === 'fit') { setZoom(1); canvas.scrollTop = canvas.scrollLeft = 0; }
    else if (control === 'prev') show(selectedIndex - 1);
    else if (control === 'next') show(selectedIndex + 1);
  });
  viewer.addEventListener('keydown', event => {
    if (event.key === 'ArrowLeft') { event.preventDefault(); show(selectedIndex - 1); }
    else if (event.key === 'ArrowRight') { event.preventDefault(); show(selectedIndex + 1); }
    else if (event.key === 'Escape') { event.preventDefault(); close(); }
  });
  doc.addEventListener('click', event => {
    const button = event.target.closest('[data-plate-open]');
    if (!button) return;
    const index = PLATES.findIndex(plate => plate.id === button.dataset.plateOpen);
    if (index < 0) return;
    opener = button;
    show(index);
    originalOverflow = doc.documentElement.style.overflow;
    doc.documentElement.style.overflow = 'hidden';
    if (typeof viewer.showModal === 'function') viewer.showModal();
    else { viewer.setAttribute('open', ''); find('[data-plate-control="close"]').focus(); }
  });
}
